<?php

declare(strict_types=1);

namespace MoveElevator\Typo3ChameleonLogin\Season;

use TYPO3\CMS\Core\Core\Environment;
use TYPO3\CMS\Core\Database\ConnectionPool;
use TYPO3\CMS\Core\Resource\FileRepository;
use TYPO3\CMS\Core\Utility\GeneralUtility;

final readonly class SeasonApplier
{
    public const string TABLE = 'tx_typo3chameleonlogin_domain_model_season';
    private const string TARGET_FILE = '/system/typo3_chameleon_login.generated.php';

    public function __construct(
        private ConnectionPool $connectionPool,
        private FileRepository $fileRepository,
        private SeasonMatcher $seasonMatcher,
    ) {
    }

    /**
     * Writes the configuration of the currently active season and returns that season.
     *
     * @return array<string, mixed>|null
     */
    public function apply(): ?array
    {
        $season = $this->findActiveSeason();
        $config = [];

        if ($season !== null) {
            $image = $this->resolveImagePath((int)$season['uid']);
            if ($image !== null) {
                $config['EXTENSIONS']['backend']['loginBackgroundImage'] = $image;
            }
            $backgroundColor = (string)($season['background_color'] ?? '');
            if ($backgroundColor !== '') {
                $config['EXTENSIONS']['typo3_chameleon_login']['loginBackgroundColor'] = $backgroundColor;
            }
        }

        $this->writeConfig($config);

        return $season;
    }

    /**
     * @return array<string, mixed>|null
     */
    private function findActiveSeason(): ?array
    {
        $rows = $this->connectionPool
            ->getQueryBuilderForTable(self::TABLE)
            ->select('*')
            ->from(self::TABLE)
            ->orderBy('priority', 'DESC')
            ->addOrderBy('uid', 'ASC')
            ->executeQuery()
            ->fetchAllAssociative();

        $today = new \DateTimeImmutable('today');
        foreach ($rows as $row) {
            if ($this->seasonMatcher->isActive($row, $today)) {
                return $row;
            }
        }

        return null;
    }

    private function resolveImagePath(int $uid): ?string
    {
        $references = $this->fileRepository->findByRelation(self::TABLE, 'image', $uid);
        if ($references === []) {
            return null;
        }

        $url = $references[0]->getOriginalFile()->getPublicUrl();
        if ($url === null || $url === '') {
            return null;
        }

        // Defense in depth: reject paths containing characters that could
        // break out of a CSS `url('…')` declaration when consumed downstream.
        if (preg_match('/[\'"\\\\(){};\r\n\t]/', $url) === 1) {
            return null;
        }

        return $url;
    }

    /**
     * @param array<string, mixed> $config
     */
    private function writeConfig(array $config): void
    {
        $target = Environment::getConfigPath() . self::TARGET_FILE;

        $php = "<?php\n"
            . "// Generated by typo3_chameleon_login, do not edit manually.\n"
            . 'return ' . $this->exportArray($config, 0) . ";\n";

        GeneralUtility::writeFile($target, $php, true);

        // Invalidate OPcache so ext_localconf.php picks up the new file on the next request
        if (function_exists('opcache_invalidate')) {
            opcache_invalidate($target, true);
        }
    }

    /**
     * @param array<array-key, mixed> $data
     */
    private function exportArray(array $data, int $depth): string
    {
        if ($data === []) {
            return '[]';
        }

        $pad = str_repeat('    ', $depth);
        $padInner = str_repeat('    ', $depth + 1);
        $lines = ['['];
        foreach ($data as $key => $value) {
            $keyExport = var_export($key, true);
            $valueExport = is_array($value)
                ? $this->exportArray($value, $depth + 1)
                : var_export($value, true);
            $lines[] = "{$padInner}{$keyExport} => {$valueExport},";
        }
        $lines[] = "{$pad}]";

        return implode("\n", $lines);
    }
}
